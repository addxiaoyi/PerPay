import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { it } from "node:test";
import { createApp } from "../src/http/app.ts";
import { listMerchantFees, readMerchantFeeHistory } from "../src/epay-compat/merchant-fee-admin.ts";
import { createConfiguredHttpServices, HTTP_TEST_ADMIN_PASSWORD } from "./http-fixture.ts";

it("restricts fee changes to administrators and commits compare-and-swap with audit", async () => {
  const directory = mkdtempSync(join(tmpdir(), "epay-fee-admin-"));
  const services = await createConfiguredHttpServices({ directory, apiSecret: null, collectionCodePayload: "https://qr.alipay.com/test" });
  let clock = 1_800_000_000_000;
  const dependencies = { ...services, startedAt: new Date(), clock: () => ++clock };
  let mainRole: "admin" | "owner" = "admin";
  const identityFetch: typeof fetch = async (input, init) => {
    const url = new URL(String(input));
    assert.equal(url.pathname, "/api/merchant/access");
    assert.equal(url.searchParams.get("merchantId"), "main-1");
    if (!new Headers(init?.headers).get("cookie")?.split("; ").includes("main_session=fixture")) return Response.json({ ok: false }, { status: 401 });
    return Response.json({ ok: true, merchantId: "main-1", apiId: "api-1", userId: "main-user", role: mainRole });
  };
  const app = createApp({ ...dependencies, merchantWorkspace: { identityOrigin: "http://127.0.0.1:8787", identityFetch } });
  const disabled = createApp(dependencies);
  const demo = createApp({ ...dependencies, demoMode: true, merchantWorkspace: { identityOrigin: "http://127.0.0.1:8787" } });
  const path = "/api/admin/v1/epay/merchants/1/fee";
  try {
    services.database.write(db => db.exec(`INSERT INTO epay_merchant_accounts(merchant_id,name,balance_cents,enabled,fee_rate_bps,created_at,updated_at) VALUES(1,'fixture',100,1,500,1,1);
      INSERT INTO epay_merchant_bindings VALUES('binding-1','api-1','main-1',1,1,1);
      INSERT INTO epay_orders(trade_no,out_trade_no,merchant_id,type_code,name,money_cents,notify_url,status,notify_status,notify_count,created_at,updated_at)
        VALUES('old','old',1,'alipay','fixture',1000,'https://example.test','PENDING','PENDING',0,1,1);
      INSERT INTO epay_alipay_intents(trade_no,merchant_id,app_id,seller_id,platform_public_key,amount_cents,fee_cents,created_at) VALUES('old',1,'app','seller','key',1000,50,1)`));
    assert.equal((await disabled.request(path)).status, 404);
    assert.equal((await app.request(path)).status, 401);
    assert.equal((await app.request(`${path}/history`)).status, 401);
    assert.equal((await app.request("/api/admin/v1/epay/merchants")).status, 401);
    const login = await app.request("/api/admin/v1/session/login", { method: "POST", headers: { "content-type": "application/json", origin: services.config.publicOrigin }, body: JSON.stringify({ password: HTTP_TEST_ADMIN_PASSWORD, remember_me: true }) });
    assert.equal(login.status, 200);
    const localCookie = login.headers.getSetCookie().map(value => value.split(";", 1)[0]).join("; ");
    assert.equal((await app.request(path, { headers: { cookie: localCookie } })).status, 401);
    const cookie = `${localCookie}; main_session=fixture`;
    mainRole = "owner";
    assert.equal((await app.request(path, { headers: { cookie } })).status, 403);
    mainRole = "admin";
    const session = ((await login.json()) as { data: { csrf_token: string; username: string } }).data;
    const headers = { cookie, "content-type": "application/json", origin: services.config.publicOrigin, "x-csrf-token": session.csrf_token };
    const payload = { expectedFeeBps: 500, expectedVersion: 1, feeBps: 350, reason: "contract update" };
    const post = (target: typeof app, body: unknown, extra: Record<string, string> = {}) => target.request(path, { method: "POST", headers: { ...headers, ...extra }, body: JSON.stringify(body) });
    assert.equal((await post(app, payload, { "x-csrf-token": "wrong" })).status, 403);
    assert.equal((await post(app, payload, { origin: "https://attacker.example" })).status, 403);
    assert.equal((await post(demo, payload)).status, 403);
    assert.equal((await post(app, { ...payload, actor: "forged" })).status, 422);
    assert.equal((await post(app, { ...payload, feeBps: 5001 })).status, 422);
    const before = await app.request(path, { headers: { cookie } });
    assert.equal(before.headers.get("cache-control"), "no-store");
    assert.deepEqual((await before.json() as { data: unknown }).data, { merchantId: 1, feeBps: 500, version: 1 });
    const listed = await app.request("/api/admin/v1/epay/merchants", { headers: { cookie } });
    assert.equal(listed.headers.get("cache-control"), "no-store");
    assert.deepEqual((await listed.json() as { data: unknown }).data, { merchants: [{ merchantId: 1, name: "fixture", enabled: true, feeBps: 500, version: 1 }], nextAfter: null });
    assert.equal((await app.request("/api/admin/v1/epay/merchants?after=1&after=2", { headers: { cookie } })).status, 400);
    const changed = await post(app, payload);
    assert.equal(changed.status, 200);
    const fee = (await changed.json() as { data: { feeBps: number; version: number } }).data;
    assert.equal(fee.feeBps, 350);
    assert.ok(fee.version > 1);
    assert.equal(Number(services.database.read(db => db.prepare("SELECT fee_cents FROM epay_alipay_intents WHERE trade_no='old'").get())?.fee_cents), 50);
    assert.equal((await post(app, payload)).status, 409);
    const audit = services.database.read(db => db.prepare("SELECT actor_id,subject_id,details_json FROM audit_events WHERE action='epay.merchant_fee.updated'").all());
    assert.equal(audit.length, 1);
    assert.equal(audit[0]?.actor_id, session.username);
    assert.equal(audit[0]?.subject_id, "1");
    assert.deepEqual(JSON.parse(String(audit[0]?.details_json)), { newFeeBps: 350, oldFeeBps: 500, reason: "contract update" });
    const history = await app.request(`${path}/history`, { headers: { cookie } });
    assert.equal(history.headers.get("cache-control"), "no-store");
    const historyBody = await history.json() as { data: { changes: Array<{ sequence: number; actor: string; oldFeeBps: number; newFeeBps: number; reason: string }>; nextBefore: number | null } };
    assert.equal(historyBody.data.changes.length, 1);
    assert.deepEqual({ ...historyBody.data.changes[0], sequence: 0, occurredAt: 0 }, { sequence: 0, occurredAt: 0, actor: session.username, oldFeeBps: 500, newFeeBps: 350, reason: "contract update" });
    assert.equal(historyBody.data.nextBefore, null);
    assert.equal((await app.request(`${path}/history?before=0`, { headers: { cookie } })).status, 400);
    assert.deepEqual(readMerchantFeeHistory(services.database, 1, historyBody.data.changes[0]!.sequence, 1), { changes: [], nextBefore: null });
    assert.deepEqual(listMerchantFees(services.database, 1, 1), { merchants: [], nextAfter: null });
    services.database.write(db => db.exec("CREATE TRIGGER reject_fee_audit BEFORE INSERT ON audit_events WHEN NEW.action='epay.merchant_fee.updated' BEGIN SELECT RAISE(ABORT,'audit unavailable'); END"));
    const failed = await post(app, { expectedFeeBps: 350, expectedVersion: fee.version, feeBps: 400, reason: "test rollback" });
    assert.ok(failed.status >= 500);
    const after = await app.request(path, { headers: { cookie } });
    assert.deepEqual((await after.json() as { data: unknown }).data, { merchantId: 1, feeBps: 350, version: fee.version });
    services.database.write(db => db.exec("DROP TRIGGER reject_fee_audit"));
    assert.equal((await post(app, { expectedFeeBps: 350, expectedVersion: fee.version, feeBps: 400, reason: "second change" })).status, 200);
    const firstPage = readMerchantFeeHistory(services.database, 1, null, 1);
    assert.equal(firstPage.changes[0]?.reason, "second change");
    assert.ok(firstPage.nextBefore);
    const secondPage = readMerchantFeeHistory(services.database, 1, firstPage.nextBefore, 1);
    assert.equal(secondPage.changes[0]?.reason, "contract update");
    assert.equal(secondPage.nextBefore, null);
  } finally { services.database.close(); rmSync(directory, { recursive: true, force: true }); }
});
