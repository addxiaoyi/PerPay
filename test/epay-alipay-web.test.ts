import assert from "node:assert/strict";
import { generateKeyPairSync, verify } from "node:crypto";
import { it } from "node:test";
import { mainOrderFixture, mainIdentity, mainInput } from "./epay-main-native-fixture.ts";
import { accountCertificate } from "./fixtures/alipay-account-certificate.ts";
import { alipaySigningFingerprint } from "../src/epay-compat/isolated-alipay-client.ts";
import { verifyAlipayQueryAccount } from "../src/epay-compat/alipay-query-account.ts";
import { createAlipayWebGateway, createAlipayWebReturn } from "../src/epay-compat/alipay-web-route.ts";
import { createIsolatedCheckoutStatus } from "../src/epay-compat/isolated-checkout-status.ts";
import { createMainNativeOrder } from "../src/epay-compat/main-native-order.ts";
import { createMainOrderRoutes } from "../src/epay-compat/main-order-routes.ts";
import { readMainOrder } from "../src/epay-compat/main-order-view.ts";
import { queryAndConfirmAlipaySubmission } from "../src/epay-compat/isolated-alipay-query.ts";
import { createV3ResponseSignature } from "../src/infrastructure/alipay/v3.ts";
import { prepareAlipayWebPayment } from "../src/epay-compat/alipay-web.ts";
import { epaySign } from "../src/epay-compat/sign.ts";
import { Hono } from "hono";

const appId = "2026000000000000", sellerId = "2088000000000000";
it("preserves web redirects, exact order identity and verified settlement without treating the return page as payment evidence", async () => {
  const signing = generateKeyPairSync("rsa", { modulusLength: 2048 });
  const f = await mainOrderFixture({ appId, sellerId, fingerprint: alipaySigningFingerprint(signing.privateKey) });
  const certificate = accountCertificate(f.directory, signing.privateKey.export({ type: "pkcs8", format: "pem" }).toString(), sellerId);
  const now = Date.now();
  const account = verifyAlipayQueryAccount({ appId, sellerId, privateKey: signing.privateKey, platformPublicKey: f.platform.publicKey.export({ type: "spki", format: "pem" }).toString(), ...certificate }, now);
  const options = { ...f, privateKey: signing.privateKey, account, notifyUrl: "https://gateway.example/pay/epay/alipay/notify", returnBase: "https://gateway.example/pay/epay/alipay/return",
    appCertSn: "a".repeat(32), alipayRootCertSn: "b".repeat(32), clock: () => now };
  const gateway = createAlipayWebGateway(options);
  try {
    const order = createMainNativeOrder({ ...f, identity: mainIdentity, input: { ...mainInput, channel: "alipay_web" }, now });
    const response = await gateway.request("/mapi.php", { method: "POST", headers: { "content-type": "application/x-www-form-urlencoded" }, body: new URLSearchParams(order.params) });
    assert.equal(response.status, 200, await response.clone().text());
    const info = await response.json() as { payurl: string; trade_no: string };
    const url = new URL(info.payurl), fields = Object.fromEntries(url.searchParams);
    assert.equal(url.origin, "https://openapi.alipay.com"); assert.equal(url.pathname, "/gateway.do");
    assert.equal(fields.method, "alipay.trade.page.pay"); assert.equal(fields.notify_url, options.notifyUrl);
    assert.equal(fields.app_cert_sn, options.appCertSn); assert.equal(fields.alipay_root_cert_sn, options.alipayRootCertSn);
    const canonical = Object.keys(fields).filter(key => key !== "sign").sort().map(key => `${key}=${fields[key]}`).join("&");
    assert.equal(verify("RSA-SHA256", Buffer.from(canonical), signing.publicKey, Buffer.from(fields.sign!, "base64")), true);
    const business = JSON.parse(fields.biz_content!);
    assert.equal(business.out_trade_no, order.tradeNo); assert.equal(business.total_amount, "1.01"); assert.equal(business.seller_id, sellerId);
    assert.equal(business.product_code, "FAST_INSTANT_TRADE_PAY");
    assert.equal(prepareAlipayWebPayment(options, order.tradeNo), info.payurl);
    const count = (table: string) => f.database.read(sql => Number(sql.prepare(`SELECT count(*) n FROM ${table}`).get()?.n));
    assert.equal(count("epay_alipay_submissions"), 1); assert.equal(count("epay_balance_ledger"), 0);
    const state = readMainOrder(f, order.orderId, 1, now);
    assert.equal(state.channel, "alipay_web"); assert.equal(state.status, "pending_payment"); assert.equal(state.paymentUrl, info.payurl); assert.equal(state.qrCode, null);
    const main = createMainOrderRoutes({ ...f, alipay: new Hono(), alipayWeb: gateway, wechat: new Hono(), identityOrigin: "http://127.0.0.1:8787", publicOrigin: "https://gateway.example", basePath: "/pay", clock: () => now, onError: assert.fail });
    const token = new URL(fields.return_url!).searchParams.get("token")!;
    const hosted = await main.request(`/checkout/${order.orderId}?token=${token}`);
    assert.equal(hosted.status, 303); assert.equal(hosted.headers.get("location"), info.payurl);
    const returnRoute = createAlipayWebReturn(f, "/pay");
    assert.equal((await returnRoute.request(`/alipay/return?token=${token}&trade_status=TRADE_SUCCESS&total_amount=0.01`)).status, 200);
    assert.equal(count("epay_balance_ledger"), 0);
    const checkout = createIsolatedCheckoutStatus(f.database, f.masterKey, () => now);
    assert.equal((await (await checkout.request("/checkout-status", { headers: { "x-checkout-token": token } })).json() as { status: string }).status, "pending");
    const makeReply = (amount: string) => {
      const raw = JSON.stringify({ out_trade_no: order.tradeNo, trade_no: "provider-web", seller_id: sellerId, app_id: appId, trade_status: "TRADE_SUCCESS", total_amount: amount });
      const timestamp = String(Math.floor(now / 1000));
      return { status: 200, body: Buffer.from(raw), headers: { "alipay-timestamp": timestamp, "alipay-nonce": "fixture", "alipay-signature": createV3ResponseSignature(raw, timestamp, "fixture", f.platform.privateKey) } };
    };
    await assert.rejects(queryAndConfirmAlipaySubmission({ ...options, tradeNo: order.tradeNo, transport: { request: async () => makeReply("1.02") } }), /amount/);
    assert.equal(count("epay_balance_ledger"), 0);
    await queryAndConfirmAlipaySubmission({ ...options, tradeNo: order.tradeNo, transport: { request: async () => makeReply("1.01") } });
    const repeated = await queryAndConfirmAlipaySubmission({ ...options, tradeNo: order.tradeNo, transport: { request: async () => makeReply("1.01") } });
    assert.equal(repeated.paymentConfirmed, true); assert.equal(repeated.duplicate, true);
    assert.equal(count("epay_balance_ledger"), 1); assert.equal(count("epay_callback_jobs"), 1);
    assert.equal(readMainOrder(f, order.orderId, 1, now).status, "paid");
    const epay = { pid: "1", type: "alipay", out_trade_no: "epay-browser", money: "1.01", name: "page", notify_url: "https://merchant.example/notify", return_url: "https://merchant.example/return", device: "mobile" };
    const query = new URLSearchParams({ ...epay, sign: epaySign(epay, "epay-key-1"), sign_type: "MD5" });
    const page = await gateway.request(`/submit.php?${query}`);
    assert.equal(page.status, 303);
    const pageUrl = new URL(page.headers.get("location")!);
    const pageOrder = JSON.parse(pageUrl.searchParams.get("biz_content")!).out_trade_no;
    assert.notEqual(pageOrder, order.tradeNo, "same amounts must keep separate order identities");
    assert.equal(count("epay_orders"), 2);
    assert.equal(count("epay_balance_ledger"), 1);
    assert.equal((await gateway.request(`/submit.php?${query.toString().replace("1.01", "1.02")}`)).status, 400);
  } finally { f.close(); }
});
