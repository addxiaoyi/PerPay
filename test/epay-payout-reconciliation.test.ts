import assert from "node:assert/strict";
import { it } from "node:test";
import { generateKeyPairSync } from "node:crypto";
import { balanceFixture } from "./epay-live-balance-fixture.ts";
import { installBalanceOpenings, planBalanceOpenings } from "../src/epay-compat/balance-opening.ts";
import { readLiveBalance } from "../src/epay-compat/live-balance.ts";
import { addPayoutAccount, reviewPayoutAccount } from "../src/epay-compat/payout-accounts.ts";
import { requestPayout, reviewPayout } from "../src/epay-compat/payout-workflow.ts";
import { claimPayout, completePayout } from "../src/epay-compat/payout-queue.ts";
import { verifyAlipayPayoutQuery } from "../src/epay-compat/payout-evidence.ts";
import { reconcilePayoutDay, postPayoutReturn } from "../src/epay-compat/payout-reconciliation.ts";
import { verifyAlipayQueryAccount } from "../src/epay-compat/alipay-query-account.ts";
import { createV3ResponseSignature } from "../src/infrastructure/alipay/v3.ts";
import { accountCertificate } from "./fixtures/alipay-account-certificate.ts";
import type { PayoutLease } from "../src/epay-compat/payout-model.ts";
import { reconcilePayoutStatement } from "../src/epay-compat/payout-statement.ts";
import { listPayouts } from "../src/epay-compat/payout-workflow.ts";
import { auditPayouts } from "../src/epay-compat/payout-audit.ts";

it("credits a signed returned payout once, preserves the original payment and rolls back audit failures", async () => {
  const f = await balanceFixture(), signing = generateKeyPairSync("rsa", { modulusLength: 2048 }), platform = generateKeyPairSync("rsa", { modulusLength: 2048 });
  const key = platform.publicKey.export({ type: "spki", format: "pem" }).toString();
  const certificate = accountCertificate(f.directory, signing.privateKey.export({ type: "pkcs8", format: "pem" }).toString());
  let now = Date.now(); const originalTime = now;
  const account = verifyAlipayQueryAccount({ appId: "2026000000000000", sellerId: "2088000000000000", privateKey: signing.privateKey, platformPublicKey: key, ...certificate }, now);
  const owner = { merchantId: "main-1", mainApiId: "api-1", epayMerchantId: 1, userId: "owner", role: "owner" as const }, admin = { ...owner, userId: "admin", role: "admin" as const };
  const destination = { kind: "alipay" as const, holderName: "合成用户", account: "recipient@example.test" }, policy = { enabled: true, channels: { alipay: { account: account.sellerId, maxSingleCents: 900, maxDailyCents: 1000 } } };
  const signed = (lease: PayoutLease, status: string, amount = "6.00") => {
    const body = JSON.stringify({ out_biz_no: lease.outNo, order_id: "original-provider-transfer", status, trans_amount: amount });
    return verifyAlipayPayoutQuery(lease, destination, { status: 200, body: Buffer.from(body), headers: { "alipay-timestamp": String(now), "alipay-nonce": "test", "alipay-signature": createV3ResponseSignature(body, String(now), "test", platform.privateKey) } }, account, key, now);
  };
  try {
    f.db.write(sql => installBalanceOpenings(sql, f.cipher, planBalanceOpenings(sql, f.cipher, "a".repeat(64)), now));
    const recipient = addPayoutAccount(f.db, f.cipher, owner, { ...destination, requestId: "recipient-request-01" }, now);
    reviewPayoutAccount(f.db, admin, recipient.id, { decision: "approve", reference: "synthetic" }, now);
    const payout = requestPayout(f.db, owner, { requestId: "payout-request-001", accountId: recipient.id, amountCents: 600 }, policy, now);
    reviewPayout(f.db, admin, payout.id, { decision: "approve", reference: "synthetic" }, policy, now);
    const lease = claimPayout(f.db, policy, now)!;
    completePayout(f.db, lease, signed(lease, "SUCCESS"), now);
    now += 86400000;
    const returned = signed(lease, "REFUND");
    assert.throws(() => signed(lease, "REFUND", "5.99"), /amount/);
    f.db.write(sql => sql.exec("CREATE TRIGGER deny_return BEFORE INSERT ON audit_events WHEN NEW.action='epay.payout.returned' BEGIN SELECT RAISE(ABORT,'return audit failed'); END"));
    assert.throws(() => postPayoutReturn(f.db, lease.id, returned, now), /audit failed/);
    assert.equal(f.db.read(sql => readLiveBalance(sql, 1)).availableCents, 350);
    f.db.write(sql => sql.exec("DROP TRIGGER deny_return"));
    assert.equal(postPayoutReturn(f.db, lease.id, returned, now), true);
    assert.equal(postPayoutReturn(f.db, lease.id, returned, now), false);
    assert.equal(f.db.read(sql => readLiveBalance(sql, 1)).availableCents, 950);
    assert.equal(f.db.read(sql => sql.prepare("SELECT status FROM epay_payouts").get()?.status), "SUCCEEDED");
    assert.equal(Number(f.db.read(sql => sql.prepare("SELECT count(*) n FROM epay_payout_returns").get()?.n)), 1);
    const day = new Date(originalTime + 8 * 3600000).toISOString().slice(0,10);
    const report = await reconcilePayoutDay({ database: f.db, cipher: f.cipher, day, clock: () => now, adapters: { alipay: { payer: account.sellerId, execute: async job => { assert.equal(job.action, "QUERY"); return signed(job, "REFUND"); } } } });
    assert.equal(report.checked, 1); assert.equal(report.issues, 0); assert.equal(report.statementMatched, false);
    assert.equal(f.db.read(sql => readLiveBalance(sql, 1)).availableCents, 950);
    const missing = await reconcilePayoutDay({ database: f.db, cipher: f.cipher, day, clock: () => now, adapters: {} });
    assert.equal(missing.issues, 1); assert.equal(missing.status, "ATTENTION");
    assert.equal(listPayouts(f.db, owner, 1).payouts[0]?.returnedCents, 600);
    assert.equal(f.db.read(sql => auditPayouts(sql, now)).inconsistent, 0);
    const statement = { day, channel: "alipay", payer: account.sellerId, sourceSha256: "f".repeat(64), rows: [{ entryId: "statement-1", outNo: lease.outNo, providerId: "original-provider-transfer", kind: "PAYOUT", amountCents: 600, occurredAt: originalTime }] };
    assert.throws(() => reconcilePayoutStatement(f.db, owner, statement, now), /forbidden/);
    assert.equal(reconcilePayoutStatement(f.db, admin, statement, now).issues, 0);
    assert.equal(reconcilePayoutStatement(f.db, admin, statement, now).duplicate, true);
    assert.throws(() => reconcilePayoutStatement(f.db, admin, { ...statement, rows: [] }, now), /different/);
    assert.equal(reconcilePayoutStatement(f.db, admin, { ...statement, sourceSha256: "e".repeat(64), rows: [] }, now).issues, 1);
    const unknown = reconcilePayoutStatement(f.db, admin, { ...statement, sourceSha256: "d".repeat(64), rows: [...statement.rows, { ...statement.rows[0], entryId: "unknown", outNo: "d".repeat(32) }] }, now);
    assert.equal(unknown.issues, 1);
    assert.equal(f.db.read(sql => readLiveBalance(sql, 1)).availableCents, 950, "statement comparisons never move funds");
    const earlierReturned = requestPayout(f.db, owner, { requestId: "payout-request-002", accountId: recipient.id, amountCents: 600 }, policy, now);
    reviewPayout(f.db, admin, earlierReturned.id, { decision: "approve", reference: "synthetic" }, policy, now);
    const secondLease = claimPayout(f.db, policy, now)!;
    const body = JSON.stringify({ out_biz_no: secondLease.outNo, order_id: "second-provider-transfer", status: "REFUND", trans_amount: "6.00" });
    const returnBeforeQuery = verifyAlipayPayoutQuery(secondLease, destination, { status: 200, body: Buffer.from(body), headers: { "alipay-timestamp": String(now), "alipay-nonce": "test", "alipay-signature": createV3ResponseSignature(body, String(now), "test", platform.privateKey) } }, account, key, now);
    assert.equal(completePayout(f.db, secondLease, returnBeforeQuery, now), true);
    assert.equal(completePayout(f.db, secondLease, returnBeforeQuery, now), false);
    assert.equal(f.db.read(sql => readLiveBalance(sql, 1)).availableCents, 950);
    assert.equal(f.db.read(sql => auditPayouts(sql, now)).inconsistent, 0);
  } finally { f.close(); }
});
